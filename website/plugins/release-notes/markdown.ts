import type {Element, ElementContent, Root as HastRoot, RootContent as HastRootContent} from 'hast';
import type {Link, Root as MdRoot, RootContent as MdRootContent} from 'mdast';
import {findAndReplace} from 'mdast-util-find-and-replace';
import {toString} from 'mdast-util-to-string';
import rehypeRaw from 'rehype-raw';
import remarkGfm from 'remark-gfm';
import remarkParse from 'remark-parse';
import remarkRehype from 'remark-rehype';
import {unified} from 'unified';
import {SKIP, visit} from 'unist-util-visit';

import type {
  RawRelease,
  ReleaseCategory,
  ReleaseNote,
  ReleaseSummaryItem,
} from '../../src/components/ReleaseNotes/types';

const DatePattern = /\d{4}-\d{2}-\d{2}/;

const AutoGeneratedHeadings = ["what's changed", 'new contributors'];

const CategoryByHeading: Record<string, ReleaseCategory> = {
  'new feature': 'feature',
  'new features': 'feature',
  feature: 'feature',
  features: 'feature',
  'bug fixed': 'fix',
  'bug fixes': 'fix',
  'bug fix': 'fix',
  fixed: 'fix',
  fixes: 'fix',
  done: 'change',
  changes: 'change',
  changed: 'change',
  change: 'change',
  'internal housekeeping': 'housekeeping',
  housekeeping: 'housekeeping',
};

const normalizeText = (text: string): string => text.trim().replace(/’/g, "'").toLowerCase();

const parseMarkdown = (body: string): MdRoot => {
  const processor = unified().use(remarkParse).use(remarkGfm);
  return processor.runSync(processor.parse(body)) as MdRoot;
};

const findFirstLink = (node: MdRootContent): Link | undefined => {
  let found: Link | undefined;
  visit(node, 'link', (link: Link) => {
    if (!found) {
      found = link;
    }
  });
  return found;
};

/** Removes the `## [x.y.z](milestone URL) - date` title heading, and returns its milestone URL and date. */
const takeTitleHeading = (
  children: MdRootContent[],
  version: string,
): {children: MdRootContent[]; milestoneUrl: string | null; date: string | null} => {
  const [first, ...rest] = children;
  if (first?.type === 'heading') {
    const text = toString(first).trim();
    if (text.startsWith(`[${version}]`) || text.startsWith(version)) {
      const link = first.children.find((child): child is Link => child.type === 'link');
      return {
        children: rest,
        milestoneUrl: link?.url ?? null,
        date: text.match(DatePattern)?.[0] ?? null,
      };
    }
  }
  return {children, milestoneUrl: null, date: null};
};

/** Splits the curated part from the GitHub auto-generated part ("What's Changed", "New Contributors"). */
const splitAutoGenerated = (
  children: MdRootContent[],
): {curated: MdRootContent[]; autoGenerated: MdRootContent[]} => {
  const splitIndex = children.findIndex(
    child => child.type === 'heading' && AutoGeneratedHeadings.includes(normalizeText(toString(child))),
  );
  if (splitIndex < 0) {
    return {curated: children, autoGenerated: []};
  }
  const curated = children.slice(0, splitIndex);
  const last = curated[curated.length - 1];
  return {
    curated: last?.type === 'thematicBreak' ? curated.slice(0, -1) : curated,
    autoGenerated: children.slice(splitIndex),
  };
};

/** Removes the `**Full Changelog**: <compare URL>` paragraph, and returns its compare URL. */
const takeCompareUrl = (
  children: MdRootContent[],
): {children: MdRootContent[]; compareUrl: string | null} => {
  const index = children.findIndex(
    child =>
      child.type === 'paragraph' &&
      child.children[0]?.type === 'strong' &&
      toString(child.children[0]).trim() === 'Full Changelog',
  );
  if (index < 0) {
    return {children, compareUrl: null};
  }
  return {
    children: children.filter((_, i) => i !== index),
    compareUrl: findFirstLink(children[index])?.url ?? null,
  };
};

const summarize = (curated: MdRootContent[]): ReleaseSummaryItem[] => {
  const counts = new Map<ReleaseCategory, number>();
  let category: ReleaseCategory = 'other';
  curated.forEach(child => {
    if (child.type === 'heading' && child.depth === 2) {
      category = CategoryByHeading[normalizeText(toString(child))] ?? 'other';
    } else if (child.type === 'list') {
      counts.set(category, (counts.get(category) ?? 0) + child.children.length);
    }
  });
  return Array.from(counts, ([category, count]) => ({category, count})).filter(item => item.count > 0);
};

const textLink = (url: string, text: string): Link => ({
  type: 'link',
  url,
  children: [{type: 'text', value: text}],
});

const addGitHubLinks = (tree: MdRoot, repoUrl: string): void => {
  findAndReplace(
    tree,
    [
      [/(?<![\w/&])#(\d+)\b/g, (value: string, issueNumber: string) => textLink(`${repoUrl}/issues/${issueNumber}`, value)],
      [
        /(?<![\w/])@([A-Za-z0-9][A-Za-z0-9-]{0,38})/g,
        (value: string, username: string) => textLink(`https://github.com/${username}`, value),
      ],
    ],
    {ignore: ['link', 'linkReference', 'inlineCode', 'code']},
  );
};

const textOf = (node: ElementContent | HastRootContent): string => {
  if (node.type === 'text') {
    return node.value;
  }
  if (node.type === 'element') {
    return node.children.map(textOf).join('');
  }
  return '';
};

const codeLanguage = (code: Element): string => {
  const className = code.properties.className;
  const classNames = Array.isArray(className) ? className.map(String) : [];
  const language = classNames.find(name => name.startsWith('language-'))?.slice('language-'.length);
  if (!language) {
    return 'text';
  }
  return language === 'sbt' ? 'scala' : language;
};

const toHast = (tree: MdRoot): HastRoot => {
  const processor = unified().use(remarkRehype, {allowDangerousHtml: true}).use(rehypeRaw);
  const hast = processor.runSync(tree) as HastRoot;

  visit(hast, 'element', (node: Element, index, parent) => {
    const headingLevel = node.tagName.match(/^h([1-6])$/)?.[1];
    if (headingLevel) {
      node.tagName = `h${Math.min(6, Math.max(4, Number(headingLevel) + 2))}`;
    }

    if (node.tagName === 'a') {
      const href = node.properties.href;
      if (typeof href === 'string' && /^https?:\/\//.test(href)) {
        node.properties.target = '_blank';
        node.properties.rel = ['noopener', 'noreferrer'];
      }
    }

    if (node.tagName === 'pre' && parent && index !== undefined) {
      const code = node.children.find(
        (child): child is Element => child.type === 'element' && child.tagName === 'code',
      );
      if (code) {
        parent.children[index] = {
          type: 'element',
          tagName: 'release-code-block',
          properties: {
            dataLanguage: codeLanguage(code),
            dataCode: textOf(code).replace(/\n$/, ''),
          },
          children: [],
        };
        return SKIP;
      }
    }
    return undefined;
  });

  visit(hast, node => {
    delete node.position;
  });

  return hast;
};

export function processRelease(raw: RawRelease, repoUrl: string, latestTagName: string | null): ReleaseNote {
  const version = raw.tagName.replace(/^v/, '');

  const parsed = parseMarkdown(raw.body);
  const title = takeTitleHeading(parsed.children, version);
  const date = title.date ?? raw.publishedAt?.slice(0, 10) ?? null;

  const {curated, autoGenerated: autoGeneratedWithCompare} = splitAutoGenerated(title.children);
  const {children: autoGenerated, compareUrl} = takeCompareUrl(autoGeneratedWithCompare);

  const summary = summarize(curated);

  const curatedRoot: MdRoot = {type: 'root', children: curated};
  const autoGeneratedRoot: MdRoot = {type: 'root', children: autoGenerated};
  addGitHubLinks(curatedRoot, repoUrl);
  addGitHubLinks(autoGeneratedRoot, repoUrl);

  const searchText = [version, toString(curatedRoot), toString(autoGeneratedRoot)].join(' ').toLowerCase();

  return {
    version,
    tagName: raw.tagName,
    htmlUrl: raw.htmlUrl,
    date,
    milestoneUrl: title.milestoneUrl,
    compareUrl,
    prerelease: raw.prerelease,
    latest: raw.tagName === latestTagName,
    summary,
    body: toHast(curatedRoot),
    autoGenerated: autoGenerated.length > 0 ? toHast(autoGeneratedRoot) : null,
    searchText,
  };
}
