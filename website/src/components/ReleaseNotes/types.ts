import type {Root} from 'hast';

export type HastRoot = Root;

export type ReleaseCategory = 'feature' | 'fix' | 'change' | 'housekeeping' | 'other';

export type ReleaseSummaryItem = {
  category: ReleaseCategory;
  count: number;
};

/** One item of `releases.json` written by `docsTools.writeReleases` in sbt. */
export type RawRelease = {
  tagName: string;
  name: string | null;
  publishedAt: string | null;
  htmlUrl: string;
  prerelease: boolean;
  body: string;
};

export type ReleaseNote = {
  version: string;
  tagName: string;
  htmlUrl: string;
  /** `YYYY-MM-DD` */
  date: string | null;
  milestoneUrl: string | null;
  compareUrl: string | null;
  prerelease: boolean;
  latest: boolean;
  summary: ReleaseSummaryItem[];
  body: HastRoot;
  autoGenerated: HastRoot | null;
  searchText: string;
};

export type ReleaseNotesData = {
  repoUrl: string;
  releases: ReleaseNote[];
};
