import React, {useEffect, useState} from 'react';
import clsx from 'clsx';
import {Collapsible, useCollapsible} from '@docusaurus/theme-common';
import useBaseUrl from '@docusaurus/useBaseUrl';

import type {ReleaseCategory, ReleaseNote, ReleaseSummaryItem} from './types';
import ReleaseBody from './ReleaseBody';
import RelativeDate from './RelativeDate';
import styles from './styles.module.css';

const CategoryLabels: Record<ReleaseCategory, {one: string; many: string}> = {
  feature: {one: 'feature', many: 'features'},
  fix: {one: 'fix', many: 'fixes'},
  change: {one: 'change', many: 'changes'},
  housekeeping: {one: 'housekeeping', many: 'housekeeping'},
  other: {one: 'other', many: 'other'},
};

const CategoryClassNames: Record<ReleaseCategory, string> = {
  feature: styles.chipFeature,
  fix: styles.chipFix,
  change: styles.chipChange,
  housekeeping: styles.chipHousekeeping,
  other: styles.chipOther,
};

function SummaryChip({item}: {item: ReleaseSummaryItem}): React.JSX.Element {
  const label = CategoryLabels[item.category];
  return (
    <span className={clsx(styles.chip, CategoryClassNames[item.category])}>
      {item.count} {item.count === 1 ? label.one : label.many}
    </span>
  );
}

function ExternalLink({href, children}: {href: string; children: React.ReactNode}): React.JSX.Element {
  return (
    <a className={styles.barLink} href={href} target="_blank" rel="noopener noreferrer">
      {children}
    </a>
  );
}

function CopyLinkButton({version}: {version: string}): React.JSX.Element {
  const pagePath = useBaseUrl('/release-notes');
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    if (!copied) {
      return undefined;
    }
    const timer = window.setTimeout(() => setCopied(false), 2000);
    return () => window.clearTimeout(timer);
  }, [copied]);

  const copy = () => {
    navigator.clipboard
      .writeText(`${window.location.origin}${pagePath}#${version}`)
      .then(() => setCopied(true))
      .catch(() => setCopied(false));
  };

  return (
    <button type="button" className={styles.barLinkButton} onClick={copy}>
      {copied ? 'Copied' : 'Copy link'}
    </button>
  );
}

function AutoGeneratedSection({release}: {release: ReleaseNote}): React.JSX.Element | null {
  const {collapsed, toggleCollapsed} = useCollapsible({initialState: true});
  if (!release.autoGenerated) {
    return null;
  }
  const bodyId = `release-${release.version}-auto-generated`;
  return (
    <div className={styles.autoGenerated}>
      <button
        type="button"
        className={styles.autoGeneratedToggle}
        aria-expanded={!collapsed}
        aria-controls={bodyId}
        onClick={toggleCollapsed}>
        <span className={clsx(styles.chevron, !collapsed && styles.chevronExpanded)} aria-hidden="true" />
        Pull requests and contributors
      </button>
      <Collapsible lazy={false} collapsed={collapsed}>
        <div id={bodyId}>
          <ReleaseBody tree={release.autoGenerated} />
        </div>
      </Collapsible>
    </div>
  );
}

type ReleaseItemProps = {
  release: ReleaseNote;
  repoUrl: string;
  expanded: boolean;
  onToggle: () => void;
};

export default function ReleaseItem({release, expanded, onToggle}: ReleaseItemProps): React.JSX.Element {
  const bodyId = `release-${release.version}-body`;
  return (
    <article
      id={release.version}
      className={clsx(styles.releaseItem, release.latest && styles.releaseItemLatest)}>
      <div className={styles.bar}>
        <h3 className={styles.barHeading}>
          <button
            type="button"
            className={styles.barButton}
            aria-expanded={expanded}
            aria-controls={bodyId}
            onClick={onToggle}>
            <span className={clsx(styles.chevron, expanded && styles.chevronExpanded)} aria-hidden="true" />
            <span className={styles.version}>v{release.version}</span>
            {release.latest && <span className="badge badge--primary">Latest</span>}
            {release.prerelease && <span className="badge badge--warning">Pre-release</span>}
            {release.date && (
              <span className={styles.date}>
                <time dateTime={release.date}>{release.date}</time>
                <RelativeDate date={release.date} />
              </span>
            )}
            {release.summary.length > 0 && (
              <span className={styles.chips}>
                {release.summary.map(item => (
                  <SummaryChip key={item.category} item={item} />
                ))}
              </span>
            )}
          </button>
        </h3>
        <div className={styles.barLinks}>
          <ExternalLink href={release.htmlUrl}>Release</ExternalLink>
          {release.milestoneUrl && <ExternalLink href={release.milestoneUrl}>Milestone</ExternalLink>}
          {release.compareUrl && <ExternalLink href={release.compareUrl}>Diff</ExternalLink>}
          <CopyLinkButton version={release.version} />
        </div>
      </div>
      <Collapsible lazy={false} collapsed={!expanded}>
        <div id={bodyId} className={styles.releaseContent}>
          <ReleaseBody tree={release.body} />
          <AutoGeneratedSection release={release} />
        </div>
      </Collapsible>
    </article>
  );
}
